/* --- build an icosphere once: vertices + faces + which faces are land --- */
export const ICO = (() => {
  const t = (1 + Math.sqrt(5)) / 2;
  let verts = [
    [-1,t,0],[1,t,0],[-1,-t,0],[1,-t,0],
    [0,-1,t],[0,1,t],[0,-1,-t],[0,1,-t],
    [t,0,-1],[t,0,1],[-t,0,-1],[-t,0,1],
  ].map((v) => { const l = Math.hypot(v[0],v[1],v[2]); return [v[0]/l, v[1]/l, v[2]/l]; });
  let faces = [
    [0,11,5],[0,5,1],[0,1,7],[0,7,10],[0,10,11],
    [1,5,9],[5,11,4],[11,10,2],[10,7,6],[7,1,8],
    [3,9,4],[3,4,2],[3,2,6],[3,6,8],[3,8,9],
    [4,9,5],[2,4,11],[6,2,10],[8,6,7],[9,8,1],
  ];
  const mid = (a, b, cache) => {
    const key = a < b ? a + "_" + b : b + "_" + a;
    if (cache[key] !== undefined) return cache[key];
    const va = verts[a], vb = verts[b];
    const m = [(va[0]+vb[0])/2, (va[1]+vb[1])/2, (va[2]+vb[2])/2];
    const l = Math.hypot(m[0],m[1],m[2]);
    verts.push([m[0]/l, m[1]/l, m[2]/l]);
    cache[key] = verts.length - 1;
    return cache[key];
  };
  for (let s = 0; s < 3; s++) {            /* 3 subdivisions = 1280 facets */
    const cache = {}, next = [];
    for (const [a,b,c] of faces) {
      const ab = mid(a,b,cache), bc = mid(b,c,cache), ca = mid(c,a,cache);
      next.push([a,ab,ca],[b,bc,ab],[c,ca,bc],[ab,bc,ca]);
    }
    faces = next;
  }
  /* is a lat/lon inside any land polygon? */
  const inPoly = (lat, lon, poly) => {
    let inside = false;
    for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
      const [yi, xi] = poly[i], [yj, xj] = poly[j];
      if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
    }
    return inside;
  };
  const built = faces.map((f) => {
    const a = verts[f[0]], b = verts[f[1]], c = verts[f[2]];
    const cx = (a[0]+b[0]+c[0])/3, cy = (a[1]+b[1]+c[1])/3, cz = (a[2]+b[2]+c[2])/3;
    const l = Math.hypot(cx,cy,cz);
    const n = [cx/l, cy/l, cz/l];
    const lat = Math.asin(n[1]) * 180 / Math.PI;
    const lon = Math.atan2(n[0], n[2]) * 180 / Math.PI;
    const land = GLOBE_LAND.some((poly) => inPoly(lat, lon, poly));
    return { v: [a, b, c], n, land };
  });
  return built;
})();

