#!/usr/bin/env node
// Builds src/data/world-cities.js: every NON-US metro served by a large
// scheduled-service airport, as an origin the app can offer worldwide.
//
// Two free sources, no token, no signup:
//   • OurAirports (public domain)  — which airports are "large" with scheduled
//     service and an IATA code. This is the size filter: ~1,150 airports.
//   • Travelpayouts data files      — the METRO code, coordinates and country
//     for each of those airports. Using the price API's own city list means
//     the code we ask /api/cheapest for is, by construction, a code the
//     nightly puller can price (LON not LHR, PAR not CDG, TYO not NRT).
//
// Output is COMMITTED. Re-run when you want a fresher list:
//   npm run build:world
//
// Names carry the country ("London, United Kingdom") so they never collide
// with the hand-curated US list in cities.js, which stays exactly as it is.
import { writeFileSync } from "node:fs";

const SRC = {
  airports: "https://davidmegginson.github.io/ourairports-data/airports.csv",
  tpAirports: "https://api.travelpayouts.com/data/en/airports.json",
  tpCities: "https://api.travelpayouts.com/data/en/cities.json",
  tpCountries: "https://api.travelpayouts.com/data/en/countries.json",
};

async function text(url) {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${url}: http ${r.status}`);
  return r.text();
}
const json = async (url) => JSON.parse(await text(url));

// Minimal CSV parser: OurAirports quotes every field, names may contain commas.
function parseCsv(csv) {
  const lines = csv.split("\n").filter(Boolean);
  const head = splitRow(lines[0]);
  return lines.slice(1).map((l) => Object.fromEntries(splitRow(l).map((v, i) => [head[i], v])));
}
function splitRow(line) {
  const out = [];
  let cur = "", q = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (ch === '"') { if (q && line[i + 1] === '"') { cur += '"'; i++; } else q = !q; }
    else if (ch === "," && !q) { out.push(cur); cur = ""; }
    else cur += ch;
  }
  out.push(cur);
  return out.map((s) => s.replace(/\r$/, ""));
}

const [csv, tpAirports, tpCities, tpCountries] = await Promise.all([
  text(SRC.airports), json(SRC.tpAirports), json(SRC.tpCities), json(SRC.tpCountries),
]);

const large = parseCsv(csv).filter((r) => r.type === "large_airport" && r.scheduled_service === "yes" && r.iata_code);
const airportByIata = new Map(tpAirports.map((a) => [a.code, a]));
const cityByCode = new Map(tpCities.map((c) => [c.code, c]));
const countryName = new Map(tpCountries.map((c) => [c.code, c.name]));
const countryCurrency = new Map(tpCountries.map((c) => [c.code, c.currency]));

const metros = new Map();
for (const r of large) {
  const a = airportByIata.get(r.iata_code);
  const c = a && cityByCode.get(a.city_code);
  if (!c || c.country_code === "US") continue; // the US list is curated by hand
  if (!c.coordinates || !Number.isFinite(c.coordinates.lat)) continue;
  if (metros.has(c.code)) continue;
  metros.set(c.code, {
    name: `${c.name}, ${countryName.get(c.country_code) ?? c.country_code}`,
    code: c.code,
    country: c.country_code,
    currency: countryCurrency.get(c.country_code) ?? "USD",
    lat: Number(c.coordinates.lat.toFixed(2)),
    lon: Number(c.coordinates.lon.toFixed(2)),
  });
}

const rows = [...metros.values()].sort((a, b) => a.country.localeCompare(b.country) || a.name.localeCompare(b.name));
if (rows.length < 500) {
  console.error(`refusing to write: only ${rows.length} world metros found (expected ~1,000) - a source changed shape?`);
  process.exit(1);
}
const dupNames = rows.map((r) => r.name).filter((n, i, arr) => arr.indexOf(n) !== i);
if (dupNames.length) {
  // two metro codes, one display name: disambiguate with the code so the
  // picker never shows two identical rows that resolve to different airports
  for (const r of rows) if (dupNames.includes(r.name)) r.name = `${r.name} (${r.code})`;
}

const body = rows.map((r) => `  { name: ${JSON.stringify(r.name)}, code: "${r.code}", country: "${r.country}", currency: "${r.currency}", lat: ${r.lat}, lon: ${r.lon} },`).join("\n");
writeFileSync("src/data/world-cities.js",
`/* GENERATED by scripts/build-world-cities.mjs — do not edit by hand.
   ${rows.length} non-US metros served by a large scheduled-service airport.
   Sources: OurAirports (public domain) + Travelpayouts city/airport data.
   Codes are Travelpayouts METRO codes, the ones the price API prices. */
export const WORLD_CITIES = [
${body}
];
`);
const countries = new Set(rows.map((r) => r.country)).size;
console.log(`wrote ${rows.length} world metros across ${countries} countries to src/data/world-cities.js`);
